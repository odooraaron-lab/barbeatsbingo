// Copies pdf.js's worker into public/ so the track list viewer can load it.
// Runs before dev and build, so it always matches the installed pdf.js version.
//
// The worker is started through a small wrapper that first adds what older iPhones
// are missing (src/lib/pdf-compat.mjs), the same fixes the page itself loads.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("pdfjs-dist/package.json"));
const { version } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
mkdirSync("public/pdfjs", { recursive: true });
copyFileSync(join(pkgDir, "legacy/build/pdf.worker.min.mjs"), "public/pdfjs/pdf.worker.min.mjs");
copyFileSync("src/lib/pdf-compat.mjs", "public/pdfjs/compat.mjs");
writeFileSync(
  "public/pdfjs/pdf.worker.compat.mjs",
  `// Generated by scripts/copy-pdf-worker.mjs: fixes for older iPhones, then pdf.js's worker.\n` +
    `import "./compat.mjs?v=${version}";\n` +
    `export * from "./pdf.worker.min.mjs?v=${version}";\n`,
);
console.log("[pdf] worker copied to public/pdfjs");
